-- 1. Add new patient
CREATE OR REPLACE PROCEDURE HMS.ADD_PATIENT(
    p_id IN VARCHAR2,
    p_name IN VARCHAR2,
    gender IN VARCHAR2,
    contact IN NUMBER,
    address IN VARCHAR2,
    dob IN DATE,
    doa IN DATE
) IS
BEGIN
