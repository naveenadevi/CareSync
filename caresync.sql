--------------------------------------------------------
--  Audit Tables
--------------------------------------------------------

CREATE TABLE HMS.PATIENT_AUDIT (
    AUDIT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    P_ID VARCHAR2(20),
    OPERATION VARCHAR2(10),
    OP_DATE DATE DEFAULT SYSDATE,
    OLD_NAME VARCHAR2(50),
    NEW_NAME VARCHAR2(50),
    OLD_CONTACT NUMBER(10),
    NEW_CONTACT NUMBER(10)
);

CREATE TABLE HMS.BILL_AUDIT (
    AUDIT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BILL_ID VARCHAR2(20),
    OPERATION VARCHAR2(10),
    OP_DATE DATE DEFAULT SYSDATE,
    OLD_ROOM_COST NUMBER,
    NEW_ROOM_COST NUMBER,
    OLD_TREATMENT_COST NUMBER,
    NEW_TREATMENT_COST NUMBER,
    OLD_OTHER_COST NUMBER,
    NEW_OTHER_COST NUMBER
);

CREATE TABLE HMS.DONE_BY_AUDIT (
    AUDIT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    T_NO VARCHAR2(20),
    OPERATION VARCHAR2(10),
    OP_DATE DATE DEFAULT SYSDATE
);

CREATE TABLE HMS.TREATED_IN_AUDIT (
    AUDIT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    P_ID VARCHAR2(20),
    ROOM_NO VARCHAR2(20),
    OPERATION VARCHAR2(10),
    OP_DATE DATE DEFAULT SYSDATE
);

--------------------------------------------------------
--  Triggers for Auditing
--------------------------------------------------------

-- PATIENT Trigger
CREATE OR REPLACE TRIGGER HMS.PATIENT_AUDIT_TRG
AFTER INSERT OR UPDATE OR DELETE ON HMS.PATIENT
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO HMS.PATIENT_AUDIT(P_ID, OPERATION, NEW_NAME, NEW_CONTACT)
        VALUES(:NEW.P_ID, 'INSERT', :NEW.P_NAME, :NEW.CONTACT);
    ELSIF UPDATING THEN
        INSERT INTO HMS.PATIENT_AUDIT(P_ID, OPERATION, OLD_NAME, NEW_NAME, OLD_CONTACT, NEW_CONTACT)
        VALUES(:OLD.P_ID, 'UPDATE', :OLD.P_NAME, :NEW.P_NAME, :OLD.CONTACT, :NEW.CONTACT);
    ELSIF DELETING THEN
        INSERT INTO HMS.PATIENT_AUDIT(P_ID, OPERATION, OLD_NAME, OLD_CONTACT)
        VALUES(:OLD.P_ID, 'DELETE', :OLD.P_NAME, :OLD.CONTACT);
    END IF;
END;
