-- 3. Generate Bill
CREATE OR REPLACE PROCEDURE HMS.GENERATE_BILL(
    p_id IN VARCHAR2
) IS
    v_room_cost NUMBER := 0;
    v_treatment_cost NUMBER := 0;
    v_other_cost NUMBER := 0;
BEGIN
    -- Calculate room cost
    SELECT SUM(r.RENT * t.NO_OF_DAYS)
    INTO v_room_cost
    FROM HMS.TREATED_IN t JOIN HMS.ROOM r
    ON t.ROOM_NO = r.ROOM_NO
    WHERE t.P_ID = p_id;

    -- Calculate treatment cost
    SELECT SUM(tr.COST)
    INTO v_treatment_cost
    FROM HMS.DONE_BY d JOIN HMS.TREATMENTS tr
    ON d.T_ID = tr.T_ID
    WHERE d.P_ID = p_id;

    -- You can add other costs manually or default to 0
    v_other_cost := 0;

    -- Insert into BILL table
    INSERT INTO HMS.BILL(BILL_ID,ROOM_COST,TREATMENT_COST,OTHER_COST)
    VALUES(p_id,v_room_cost,v_treatment_cost,v_other_cost);

    COMMIT;
END;
